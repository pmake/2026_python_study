import plotly.express as px
import pandas as pd

# 模擬顧客行為資料
df = pd.DataFrame({
    '性別': ['男','女','男','女','男','女','男','女','男','女'],
    '年齡層': ['20-29','20-29','30-39','30-39','40-49','40-49','50-59','50-59','60+','60+'],
    '購買品類': ['服飾','美妝','3C','服飾','食品','3C','食品','美妝','服飾','3C'],
    '付款方式': ['信用卡','行動支付','信用卡','貨到付款','信用卡','行動支付','信用卡','貨到付款','行動支付','信用卡']
})

# 建立平行類別圖
fig = px.parallel_categories(
    df,
    dimensions=['性別','年齡層','購買品類','付款方式'],
    color_continuous_scale=px.colors.sequential.Inferno,
    title='顧客購買行為平行類別圖'
)

fig.show()