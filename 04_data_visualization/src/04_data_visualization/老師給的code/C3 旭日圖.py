import plotly.express as px
import pandas as pd

# 建立階層資料
df = pd.DataFrame({
    '部門': ['行銷', '行銷', '行銷', '研發', '研發', '業務', '業務', '業務', '業務'],
    '子部門': ['數位行銷', '活動推廣', '品牌策略', '產品開發', '測試', '北區', '中區', '南區', '海外'],
    '產品線': ['社群廣告', '展覽活動', '品牌合作', 'App開發', '品質測試', '通路零售', '加盟銷售', '直營門市', '代理銷售'],
    '營收': [300, 200, 250, 400, 150, 180, 220, 260, 140]
})

# 建立旭日圖
fig = px.sunburst(
    df,
    path=['部門', '子部門', '產品線'],  # 定義階層順序
    values='營收',                     # 每個節點的數值
    color='部門',                      # 按部門著色
    title='公司營收結構旭日圖（多層級階層關係）'
)

fig.show()